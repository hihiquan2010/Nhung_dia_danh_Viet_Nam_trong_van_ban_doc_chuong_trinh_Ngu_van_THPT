export function getAllPlaces() {
  return menuData.flatMap((gradeItem) =>
    (gradeItem.works || []).flatMap((work) =>
      (work.places || []).map((place) => ({
        ...place,
        grade: gradeItem.grade,
        work: work.name,
      })),
    ),
  );
}

export function buildPageMap() {
  return getAllPlaces().reduce((pageMap, place) => {
    const fileName = place.url.split("/").pop();
    pageMap[place.name] = fileName;
    return pageMap;
  }, {});
}

export function resolvePlaceUrl(placeUrl) {
  const fileName = placeUrl.split("/").pop();
  return `./html/${fileName}`;
}
